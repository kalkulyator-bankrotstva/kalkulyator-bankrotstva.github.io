// Логика «подходит ли банкротство». Нормы сверены 01.10.2026 по КонсультантПлюс:
// 127-ФЗ ст. 213.3, 213.4, 20.6, 223.2, 223.6; НК 333.21 пп.8; ГПК 446. Пересказом: 213.28, 213.30 (перепроверить).
(function (root) {
  'use strict';
  const MFC_MIN = 25000, MFC_MAX = 1000000, DUTY_MIN = 500000, DEPOSIT = 25000;

  function assess(a) {
    const debt = +a.debt || 0;
    const r = { code: '', title: '', text: '', cost: '', term: '', flags: [], docs: [] };
    if (a.bankrupt5y) {
      return { ...r, code: 'later', title: 'Сейчас недоступно',
        text: 'После банкротства подать на себя снова можно только через 5 лет. Пока - переговоры с кредиторами, реструктуризация, кредитные каникулы.' };
    }
    if (debt < MFC_MIN) {
      return { ...r, code: 'no', title: 'Банкротство не нужно',
        text: 'Долг меньше 25 000 ₽ - банкротство не подходит и не окупится. Попросите у кредитора рассрочку или реструктуризацию.' };
    }
    const ip = a.ip || 'none'; // none | active | returned
    const noProperty = !a.extraRealty && !a.car && !a.valuables;
    const ipYears = +a.ipYears || 0;
    const social = a.income === 'pension' || a.income === 'svo' || a.income === 'childbenefit';
    const mfcBasis =
      (ip === 'returned' && !a.otherActiveIp) ? 'исполнительное производство окончено возвратом документа взыскателю, других нет' :
      (social && ip !== 'none' && ipYears >= 1 && noProperty) ? 'основной доход - пенсия, выплаты участнику СВО или единое пособие, взыскание идёт больше года, имущества нет' :
      (ip !== 'none' && ipYears >= 7) ? 'исполнительный документ предъявлен 7 и более лет назад и не исполнен' : '';
    const canPay = a.canPay === true;
    if (debt <= MFC_MAX && mfcBasis && !a.extrajudicial5y) {
      Object.assign(r, { code: 'mfc', title: 'Подходит бесплатное банкротство через МФЦ',
        text: 'Основание: ' + mfcBasis + '. Юрист и суд не нужны: заявление подаётся в МФЦ.',
        cost: '0 ₽', term: '6 месяцев' });
      r.docs = ['Паспорт', 'СНИЛС', 'Список всех кредиторов с суммами (по форме МФЦ) - не указанные в заявлении долги не спишутся',
        'Постановление об окончании исполнительного производства (банк данных ФССП)'];
    } else if (debt >= DUTY_MIN && a.overdue3m) {
      Object.assign(r, { code: 'court-duty', title: 'Нужно подавать на банкротство через суд',
        text: 'Долг от 500 000 ₽ и платежи просрочены больше 3 месяцев: закон обязывает подать заявление в течение 30 рабочих дней.',
        cost: 'депозит ' + DEPOSIT.toLocaleString('ru-RU') + ' ₽ на финансового управляющего + расходы на публикации; госпошлина не взимается',
        term: 'обычно 6-12 месяцев' });
    } else if (!canPay) {
      Object.assign(r, { code: 'court-right', title: 'Можно подать на банкротство через суд',
        text: debt < DUTY_MIN ? 'Обязанности подавать нет, но право есть, если вы не можете платить по долгам.' : 'Обязанности пока нет (просрочка меньше 3 месяцев), но если платить нечем - подать можно заранее.',
        cost: 'депозит ' + DEPOSIT.toLocaleString('ru-RU') + ' ₽ на финансового управляющего + расходы на публикации; госпошлина не взимается',
        term: 'обычно 6-12 месяцев' });
    } else {
      return { ...r, code: 'pay', title: 'Банкротство пока не нужно',
        text: 'Если вы можете платить по графику, сначала посчитайте план погашения - банкротство несёт ограничения на 5 лет.' };
    }
    if (r.code !== 'mfc') r.docs = ['Паспорт, СНИЛС, ИНН', 'Кредитные договоры и справки о задолженности', 'Справки о доходах за 3 года',
      'Документы на имущество и сделки за 3 года', 'Кредитная история (бюро кредитных историй)'];
    // флаги риска
    if (a.nonDischarge) r.flags.push('Алименты, вред здоровью, субсидиарная ответственность и некоторые другие долги не списываются.');
    if (a.mortgage) r.flags.push('Жильё в ипотеке защищено не будет: залог реализуют, даже если это единственное жильё.');
    if (a.extraRealty) r.flags.push('Второе жильё, дача или земля (кроме единственного жилья) могут быть проданы для расчётов с кредиторами.');
    if (a.car) r.flags.push('Автомобиль, скорее всего, продадут (кроме отдельных исключений по закону).');
    if (a.deals3y) r.flags.push('Сделки за последние 3 года (продажа, дарение, переоформление имущества) могут оспорить.');
    if (a.director) r.flags.push('После банкротства 3 года нельзя руководить компанией.');
    if ((+a.incomeMonthly || 0) > 0 && r.code.startsWith('court') && +a.incomeMonthly * 36 > debt * 0.5)
      r.flags.push('Доход заметный: суд может ввести реструктуризацию долга вместо списания.');
    if (debt > MFC_MAX && mfcBasis) r.flags.push('Для МФЦ долг должен быть не больше 1 000 000 ₽.');
    return r;
  }

  const api = { assess, MFC_MIN, MFC_MAX, DUTY_MIN, DEPOSIT };
  if (typeof module !== 'undefined' && module.exports) module.exports = api; else root.BankruptEngine = api;
})(typeof self !== 'undefined' ? self : this);
